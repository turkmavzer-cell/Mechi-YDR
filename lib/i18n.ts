interface LocalizationContextType {
    language: string;
    t: (key: string) => string;
}

const LocalizationContext = createContext<LocalizationContextType | undefined>(undefined);

export const LocalizationProvider: React.FC<{ language: string; children: React.ReactNode }> = ({ language, children }) => {
    const t = useMemo(() => {
        return (key: string): string => {
            const langPrefix = language.split('-')[0];
            const langKey = Object.keys(translations).find(k => k.startsWith(langPrefix)) || 'tr-TR';
            return translations[langKey]?.[key] || translations['tr-TR'][key] || key;
        };
    }, [language]);

    const value = { language, t };
    
    return React.createElement(LocalizationContext.Provider, { value }, children);
};

export const useLocalization = (): LocalizationContextType => {
    const context = useContext(LocalizationContext);
    if (context === undefined) {
        throw new Error('useLocalization must be used within a LocalizationProvider');
    }
    return context;
};